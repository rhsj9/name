def add_book(library):
    # Запрашиваем данные у пользователя и убираем лишние пробелы по краям
    title = input("Введите название книги: ").strip()
    author = input("Введите автора книги: ").strip()
    year = input("Введите год издания: ").strip()

    # Проверяем, что название и автор не пустые, а год состоит только из цифр
    if not title or not author or not year.isdigit():
        print("Ошибка: название и автор не могут быть пустыми, а год должен быть числом.")
        return  # Прерываем выполнение функции без добавления книги

    # Создаем словарь с данными книги (год оставляем строкой или переводим в int)
    new_book = {
        'title': title,
        'author': author,
        'year': year
    }

    # Добавляем словарь в общий список и сообщаем об успехе
    library.append(new_book)
    print("Книга добавлена в каталог")
